const dayNames = [
  "Read the chapter into code",
  "Trace one input",
  "Lock it with a test",
  "The same rule in JavaScript",
  "What the model must not add",
  "Run it on J.R.",
  "Rewrite from a blank file",
];

function choiceFor(core, day) {
  const prompt = `Week ${core.week}, day ${day}. ${core.domain} is the chapter. What does this week's function refuse to do?`;
  return choice(
    prompt,
    [
      "It fills a missing clinical fact so the packet looks finished.",
      "It reports a gap, a missing value, or a stop, and it does not invent the chart.",
      "It submits the request when the text is fluent.",
      "It trains on last year’s paid letters.",
    ],
    "b",
    `${core.blurb} Invention and unsupervised sending stay outside the function.`,
    "The code and the chapter are the same rule."
  );
}

function codeFor(core, day) {
  const forbidden = ["six weeks of therapy", "sent\": true", "while true"];
  if (day === 4) {
    return codeEx({
      prompt: `Write the JavaScript version of this week’s rule. ${core.blurb}`,
      snippets: core.jsSnippets,
      sample: core.jsSample,
      forbidden,
      correction: core.jsSample,
      why: "The language changed. The refusal did not.",
    });
  }
  if (day === 3) {
    const sample = `${core.sample}\n${core.check}`;
    return codeEx({
      prompt: `Include this week’s function and an assert that calls it, then print passed. ${core.blurb}`,
      snippets: [...core.snippets, "assert", "passed"],
      sample,
      forbidden,
      correction: sample,
      why: "The assert fails the file if a later edit starts inventing.",
    });
  }
  return codeEx({
    prompt: `Write this week’s function. ${core.blurb}`,
    snippets: core.snippets,
    sample: core.sample,
    forbidden,
    correction: core.sample,
    why: core.blurb,
  });
}

function buildDay(core, day) {
  const id = `d${String(core.week).padStart(2, "0")}-${day}`;
  const hours = [
    {
      title: "Hour 1. Read",
      time: "60 minutes",
      text: `Open “${core.domain}” and read it once without the editor. Write three sentences from memory in the note box. Do not paste a chart.`,
    },
    {
      title: "Hour 2. Trace",
      time: "60 minutes",
      text: `On paper, run today’s function by hand on one fictional input and on a missing input. ${core.blurb}`,
    },
    {
      title: "Hour 3. Type and run",
      time: "60 minutes",
      text: "Type the lab into a new file under labs/. Run it with py or node. Change one input. Run it again. If you only paste, you have not had the hour.",
    },
    {
      title: "Hour 4. Submit",
      time: "60 minutes",
      text: "Submit both exercises. Read the correction if it appears and rewrite from a blank box. Then stop. Tomorrow is a new four hours.",
    },
  ];
  return lesson({
    id,
    sequence: "days",
    trackTitle: "Daily studio",
    week: core.week,
    day,
    title: dayNames[day - 1],
    promise: core.blurb,
    keyboard: "Run the file on your machine. The studio grades the shape of the code. It does not execute it for you.",
    record: "Fiction only. J.R. and A.M. are not people in the practice. sent stays false.",
    hours: "4 hours",
    weekPlan: hours.map((item) => `${item.title}. ${item.text}`),
    sections: [
      {
        heading: "The four hours",
        blocks: [{ type: "hours", items: hours }],
      },
      prose("How this day sits in the week", [
        `This is day ${day} of week ${core.week}. The chapter is ${core.domain}. ${core.blurb}`,
        "Python is where the agent loop and the training labs live. JavaScript is where this classroom and a tool’s request live. SQL is where you will count inventions. Today’s exercise uses the language named on the lab.",
      ]),
      prose("Lab", [
        day === 4
          ? "Save the file as labs/day.js and run it with node."
          : "Save the file as labs/day.py and run it with py.",
        "After it runs, point at the line that refuses to invent. If you cannot find that line, the function is not finished.",
      ], [codeBlock(day === 4 ? "javascript" : "python", day === 4 ? core.jsSample : day === 3 ? `${core.sample}\n${core.check}` : core.sample)]),
    ],
    example: {
      title: "What a correct run is for",
      blocks: [
        {
          type: "p",
          text: `${core.blurb} When the missing input is used, the result is a hold, a gap, None, false, or the word missing. It is not a completed letter.`,
        },
      ],
    },
    exercises: [choiceFor(core, day), codeFor(core, day)],
  });
}

export const dayLessons = cores.flatMap((core) => [1, 2, 3, 4, 5, 6, 7].map((day) => buildDay(core, day)));

